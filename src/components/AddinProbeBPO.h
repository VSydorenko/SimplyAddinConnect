/// ТИМЧАСОВА зонд-компонента (гілка bpo-acquiring-prep). НЕ продуктова —
/// прибрати перед merge у main.
///
/// Знімає дві невизначеності, які блокують дизайн БПО-фасаду еквайрингу і які
/// НЕМОЖЛИВО перевірити без живої 1С:
///
///   Зонд 0.5 — IN/OUT-параметри. Контракт БПО передає НомерКарты/НомерЧека/
///   СсылочныйНомер/КодАвторизации заповненими й чекає їх назад. У наших
///   продуктових фасадах OUT-параметри завжди приходять порожніми, тож гілка
///   VariantHelper::clear() -> FreeMemory на рядку, який виділила ПЛАТФОРМА,
///   ніколи не виконувалась. `InOut9` виконує саме її.
///
///   Зонд 0.7 — чи лишається клієнтський потік 1С живим під час
///   `Ждать ОбъектДрайвера.МетодАсинх(...)`. Від цього залежить, чи можливий
///   онлайн-прогрес операції оплати взагалі: і полінг `ПодключитьОбработчикОжидания`,
///   і доставка `ВнешнееСобытие` впираються в живий цикл обробки повідомлень.
///   `BlockAndEmit` блокує потік виклику й паралельно шле події + рухає лічильник,
///   який 1С може опитувати методом `Ticks`.
class AddinProbeBPO : public AddInNative {
public:
    static std::vector<std::u16string> names;
    AddinProbeBPO();
    virtual ~AddinProbeBPO();

private:
    void RegisterMethods();

    std::atomic<int> tick_{ 0 };        ///< скільки разів емітер прокинувся (дешеве читання з 1С)
    std::atomic<int> emitted_{ 0 };     ///< скільки подій реально віддано в PostExternalEvent
    std::atomic<bool> running_{ false };///< активний BlockAndEmit (для захисту від паралельного старту)
};
